#!/usr/bin/env python3
"""export_md.py — write .claude/evolve/LEARNINGS.md, the high-reliability resurfacing
channel. Auto-skills only fire when their description matches the task; SessionStart
injection always lands but is capped. A markdown file the user @imports from CLAUDE.md is
read on EVERY turn with top priority — the surest way for Claude to actually apply lessons.

Regenerated on every consolidate. The user wires it once:  add  @.claude/evolve/LEARNINGS.md
to the project's CLAUDE.md. Usage (standalone): python3 export_md.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import store  # noqa: E402

MAX_ITEMS = int(__import__("os").environ.get("EVOLVE_MD_MAX", "25"))


def build(data: dict) -> str:
    active = [r for r in data.values() if r.get("state") == "active"]
    active.sort(key=store.confidence, reverse=True)
    active = active[:MAX_ITEMS]
    if not active:
        return ""
    groups = {"correction": [], "build_failure": [], "fix": []}
    for r in active:
        groups.get(r.get("type"), groups["fix"]).append(r)

    out = [
        "# Project learnings (auto-generated by claude-evolve)",
        "",
        "Apply these accumulated lessons; do not repeat past mistakes. This file is "
        "regenerated automatically — edit lessons via `/claude-evolve:review`, not here.",
        "",
    ]
    labels = [("correction", "Preferences & corrections"),
              ("build_failure", "Recurring build/test failures"),
              ("fix", "Known fixes")]
    for key, heading in labels:
        rows = groups.get(key) or []
        if not rows:
            continue
        out.append(f"## {heading}")
        for r in rows:
            seen = r.get("seen_count", 1)
            body = store.sanitize(r.get("body", "")).replace("\n", " ").strip()
            title = store.sanitize(r.get("title", "")).strip()
            line = f"- **(seen {seen}x)** {title}"
            if body and body[:120] not in title:
                line += f" — {body[:160]}"
            out.append(line)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write(data: dict) -> str:
    md = build(data)
    p = store.store_dir() / "LEARNINGS.md"
    if not md:
        return ""
    store.ensure_store()
    p.write_text(md)
    return str(p)


# ---- PROJECT_CONTEXT.md — separate channel for "fact" records --------------
#
# LEARNINGS.md mixes corrections/build-failures/fixes (things to NOT repeat).
# Facts are different in kind: durable background about the user/project (who they
# are, what phase they're in, standing preferences) — things to carry forward, not
# mistakes to avoid. Keeping them in their own file mirrors Hermes splitting `user`
# memory from procedural lessons, and lets a project wire it independently:
#   @.claude/evolve/PROJECT_CONTEXT.md
# Bounded by the same FACT_MAX_CHARS budget store.py enforces on the active set.

def build_context(data: dict) -> str:
    facts = [r for r in data.values()
             if r.get("type") == "fact" and r.get("state") == "active"]
    if not facts:
        return ""
    facts.sort(key=store.confidence, reverse=True)
    out = [
        "# Project context (auto-generated by claude-evolve)",
        "",
        "Durable background about this project/user, captured via explicit "
        "@remember/@note/@background/@fact markers. Treat as reference context, not "
        "instructions. Regenerated automatically — capture more via those markers, "
        "don't hand-edit this file.",
        "",
    ]
    for r in facts:
        seen = r.get("seen_count", 1)
        title = store.sanitize(r.get("title", "")).strip()
        out.append(f"- **(seen {seen}x)** {title}")
    return "\n".join(out).rstrip() + "\n"


def write_context(data: dict) -> str:
    md = build_context(data)
    p = store.store_dir() / "PROJECT_CONTEXT.md"
    if not md:
        return ""
    store.ensure_store()
    p.write_text(md)
    return str(p)


def main() -> None:
    data = store.load_learnings()
    out = write(data)
    out2 = write_context(data)
    print(f"wrote {out}" if out else "no active learnings to export")
    print(f"wrote {out2}" if out2 else "no active facts to export")


if __name__ == "__main__":
    main()
